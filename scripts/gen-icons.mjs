import { readFileSync, writeFileSync } from 'node:fs'
const html = readFileSync('design/calmon-design.html', 'utf8')
const re = /<symbol id="i-([a-z0-9-]+)" viewBox="([^"]+)">([\s\S]*?)<\/symbol>/g
const RENAME = { 'chev-r': 'chevron-right', 'chev-l': 'chevron-left', 'chev-d': 'chevron-down', 'chev-u': 'chevron-up', 'bell-off': 'bell-off' }
const pascal = (s) => (RENAME[s] ?? s).split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('')
const icons = []
let m
while ((m = re.exec(html))) icons.push({ id: m[1], viewBox: m[2], inner: m[3].trim() })
// "logo" is the product mark, not a UI icon; keep it but flag it.
const out = [
  `// GENERATED by scripts/gen-icons.mjs (from design/calmon-design.html). Do not edit by hand.`,
  `import type { SVGProps } from 'react'`,
  `import { cn } from '../lib/cn.ts'`,
  ``,
  `export type IconProps = Omit<SVGProps<SVGSVGElement>, 'children' | 'viewBox'>`,
  ``,
  `/** Decorative by default (hidden from assistive technology). Pass \`aria-label\` or \`aria-labelledby\` to make one meaningful: it then gets \`role="img"\`. */`,
  `function make(inner: string, viewBox: string) {`,
  `  return function Icon({ className, ...props }: IconProps) {`,
  `    const hidden = !(props['aria-label'] || props['aria-labelledby'])`,
  `    return (`,
  `      <svg`,
  `        viewBox={viewBox}`,
  `        width="16"`,
  `        height="16"`,
  `        role={hidden ? undefined : 'img'}`,
  `        aria-hidden={hidden ? true : undefined}`,
  `        focusable="false"`,
  `        className={cn('inline-block shrink-0 align-[-3px]', className)}`,
  `        {...props}`,
  `        dangerouslySetInnerHTML={{ __html: inner }}`,
  `      />`,
  `    )`,
  `  }`,
  `}`,
  ``,
  ...icons.map((i) => `export const ${pascal(i.id)}Icon = /* @__PURE__ */ make(${JSON.stringify(i.inner)}, ${JSON.stringify(i.viewBox)})`),
  ``,
]
writeFileSync('packages/ui/src/icons/icons.tsx', out.join('\n'))
console.log(icons.length, 'icons:', icons.map((i) => pascal(i.id) + 'Icon').join(' '))
