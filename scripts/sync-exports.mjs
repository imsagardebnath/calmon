#!/usr/bin/env node
// Keeps the package's public surface in sync with the folders in packages/ui/src, so adding a
// component never means editing package.json or a barrel by hand.
//
//   - every folder in src/ except lib, containing an index.ts, is a component entry point
//   - package.json "exports" gets "./<folder>" for each  (and "./lib" is not exported)
//   - src/index.ts is regenerated: lib helpers + `export *` from every component folder
//
// Run automatically by `npm run build`, `npm run typecheck` and `npm run dev`.

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const uiDir = join(root, 'packages/ui')
const srcDir = join(uiDir, 'src')

const folders = readdirSync(srcDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && d.name !== 'lib' && existsSync(join(srcDir, d.name, 'index.ts')))
  .map((d) => d.name)
  .sort()

// ---- package.json exports ----
const pkgPath = join(uiDir, 'package.json')
const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'))
const exports = {
  '.': pkg.exports['.'],
  './styles.css': pkg.exports['./styles.css'],
  ...Object.fromEntries(
    folders.map((f) => [`./${f}`, { types: `./dist/${f}/index.d.ts`, import: `./dist/${f}/index.js` }]),
  ),
  './package.json': './package.json',
}
const nextPkg = JSON.stringify({ ...pkg, exports }, null, 2) + '\n'
if (nextPkg !== readFileSync(pkgPath, 'utf8')) writeFileSync(pkgPath, nextPkg)

// ---- barrel ----
const barrel =
  [
    '// GENERATED by scripts/sync-exports.mjs from the folders in src/. Do not edit by hand.',
    "// Prefer per-component imports (`@openvanta/calmon-react/button`) in apps that do not tree-shake.",
    "export * from './lib/index.ts'",
    ...folders.map((f) => `export * from './${f}/index.ts'`),
  ].join('\n') + '\n'
const barrelPath = join(srcDir, 'index.ts')
if (!existsSync(barrelPath) || barrel !== readFileSync(barrelPath, 'utf8')) writeFileSync(barrelPath, barrel)

console.log(`sync-exports: ${folders.length} entry point(s): ${folders.join(', ')}`)
